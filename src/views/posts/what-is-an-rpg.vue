      they belong to that character.
    </p>

    <p>
      This is where RPGs separate themselves from many other genres. RPGs aren't just about
      optimizing builds or solving systems. They're about player expression.
    </p>

    <h2>Systems Support Roleplay, They Do Not Replace It</h2>

    <p>
      Systems don't create roleplay on their own. They enable it. Character creation, freedom
      of movement, open progression, and flexible interaction systems create a space where
      roleplay can exist meaningfully.
    </p>

    <h2>Acting Versus Roleplaying</h2>

    <p>
      This is where I struggle with many traditionally labeled RPGs like <em>Final Fantasy</em>
      or <em>Clair Obscur: Expedition 33</em>.
    </p>

    <p>
      These are excellent games, but in them you are assuming a predefined character and a
      predefined trajectory. You don't meaningfully decide who this character is. You perform
      them.
    </p>

    <p>
      Leveling up and skill trees often serve combat depth, not roleplay. Even when choices
      exist, they rarely alter the world in a meaningful way.
    </p>

    <h2>Mechanical Choice Versus Narrative Agency</h2>

    <p>
      Many games offer mechanical choice. RPGs should also offer narrative agency. When the
      world acknowledges who you are and what you've done, you start inhabiting a role instead
      of navigating a system.
    </p>

    <h2>Open Worlds and Closed Stories</h2>

    <p>
      The <em>Elder Scrolls</em> series shows this tension clearly. You can roleplay freely in
      the open world, but the main quest remains a closed story. Balancing authored narrative
      and player freedom is one of the hardest problems in RPG design.
    </p>

    <h2>Time Investment Versus Identity Investment</h2>

    <p>
      Many games ask for time. RPGs ask for identity. They reward consistency, commitment to
      a role, and long-term consequences, even when those consequences are subtle.
    </p>

    <h2>So What Makes an RPG?</h2>

    <ul>
      <li>A system with clear, consistent rules that interact with the player and the world</li>
      <li>The freedom to make meaningful choices based on a role you create or adopt</li>
      <li>A story that responds to those choices instead of ignoring them</li>
    </ul>

    <p>
      Without these, you can still have a great game. But roleplaying isn't about stats or
      skill trees. It's about inhabiting a character in a world that acknowledges your presence.
    </p>

